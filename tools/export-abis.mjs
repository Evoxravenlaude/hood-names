// Copies the ABIs the web app uses from Foundry's build output into
// app/src/abi/index.ts. Run `forge build` first.
import fs from 'node:fs';

const contracts = {
  controller: 'HoodRegistrarController',
  lens: 'HoodNameLens',
  guard: 'HoodNameGuard',
  resolver: 'HoodPublicResolver',
  reverseRegistrar: 'ReverseRegistrar',
  registry: 'ENSRegistry',
  baseRegistrar: 'HoodBaseRegistrar',
  nameWrapper: 'NameWrapper',
  policy: 'HoodResolverPolicy',
  pointsLedger: 'HoodPointsLedger',
  giftCard: 'HoodGiftCard',
  referralHub: 'HoodReferralHub',
  testUsd: 'TestUSD',
};

let out = '// Generated by tools/export-abis.mjs from the Foundry build. Do not edit.\n\n';
for (const [key, name] of Object.entries(contracts)) {
  const file = `out/${name}.sol/${name}.json`;
  const { abi } = JSON.parse(fs.readFileSync(file, 'utf8'));
  const kept = abi.filter((e) => ['function', 'event', 'error'].includes(e.type));
  out += `export const ${key}Abi = ${JSON.stringify(kept)} as const;\n\n`;
}
fs.writeFileSync('app/src/abi/index.ts', out);
console.log('Wrote app/src/abi/index.ts');
